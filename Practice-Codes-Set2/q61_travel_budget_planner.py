print(f"Hotel           : Rs. {hotel}")
print(f"Transport       : Rs. {transport}")
print(f"Food            : Rs. {food}")
print(f"Shopping        : Rs. {shopping}")
print(f"Total Expense   : Rs. {total_expense}")
print(f"Remaining Budget: Rs. {remaining}")
