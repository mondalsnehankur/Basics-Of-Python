# Q3. Fuel Cost Estimation

mileage = 45
distance = 180
price_per_litre = 105
litres_needed = distance / mileage
fuel_cost = litres_needed * price_per_litre

print("Distance        :", distance, "km")
print("Petrol Price    : Rs.", price_per_litre, "per litre")
print("Litres Needed   :", litres_needed)
print("Estimated Cost  : Rs.", fuel_cost)
