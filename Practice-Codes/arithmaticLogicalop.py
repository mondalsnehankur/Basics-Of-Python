a = 10
b = 5

# Arithmetic Operators
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)

# Comparison Operators
print("a > b:", a > b)
print("a == b:", a == b)
print("a != b:", a != b)

# Logical Operators
print("(a > b) and (b > 0):", (a > b) and (b > 0))
print("(a < b) or (b > 0):", (a < b) or (b > 0))
print("not(a < b):", not(a < b))